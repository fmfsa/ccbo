def cost_curves(units, key, cumulative=False):
    """Seed-by-cost matrix restricted to costs reached by every seed."""
    rows = [{c['cost']: c[key] for c in u['checkpoints']} for u in units]
    costs = sorted(set.intersection(*(set(r) for r in rows)))
    matrix = np.array([[r[c] for c in costs] for r in rows])
    if cumulative:
        matrix = np.cumsum(matrix, axis=1)
    return np.array(costs), matrix


def trial_curves(units, key):
    """Seed-by-trial matrix: the recommendation after each optimizer trial
    (trial 0 = after the given initial points), up to the fewest trials any
    seed of the group ran."""
    last = min(u['trials'] for u in units)
    matrix = []
    for u in units:
        row, j, points = [], 0, u['trial_points']
        for t in range(last + 1):
            while j + 1 < len(points) and points[j + 1][0] <= t:
                j += 1
            row.append(points[j][1][key])
        matrix.append(row)
    return np.arange(last + 1), np.array(matrix)


def draw(ax, x, matrix, label, steps=True):
    mean, half = band(matrix)
    plotstyle.step_band(ax, x, mean, half, label, steps=steps)


def save(fig, path):
    fig.savefig(path)          # exact figure size; include without rescaling
    plt.close(fig)


# Drawing order: baselines first (underneath), the key comparison last (on top).
FIG2_ORDER = ['BO', 'BO-S', 'CBO-NP', 'CBO (misspecified)', 'CBO', 'QCBO']
FIG2_LEGEND = ['CBO', 'QCBO', 'CBO (misspecified)', 'CBO-NP', 'BO', 'BO-S']
FIG2_PANELS = [('a', 'ParallelParent', 'A0', 'A1'), ('b', 'FrontDoor', 'B0', 'B1')]


def figure2_like(units, path, curves, xlabel):
    """ParallelParent and FrontDoor side by side (column width), shared legend."""
    fig, axes = plt.subplots(1, 2, figsize=plotstyle.size('column', 0.62))
    for ax, (letter, scm, correct, edited) in zip(axes, FIG2_PANELS):
        for label in FIG2_ORDER:
            cond, method = (edited, 'CBO') if label == 'CBO (misspecified)' else (correct, label)
            group = select(units, scm=scm, cond=cond, method=method)
            require(group, f'missing {scm} {label} results')
            draw(ax, *curves(group), label)
        plotstyle.panel_title(ax, letter, scm)
        ax.set_xlabel(xlabel)
        ax.set_ylim(bottom=-0.03 * ax.get_ylim()[1])
    axes[0].set_ylabel('Incumbent objective')
    fig.legend(plotstyle.legend_handles(FIG2_LEGEND), FIG2_LEGEND, loc='outside upper center', ncol=3,
               handlelength=2.0, columnspacing=1.0)
    save(fig, path)


def figure_cost_indexed(units, path):
    figure2_like(units, path, lambda g: cost_curves(g, 'recommendation_population'), 'Intervention cost')


def figure_trial_indexed(units, path):
    figure2_like(units, path, lambda g: trial_curves(g, 'recommendation_population'),
                 'Optimizer trial (observe or intervene)')


def figure_minimal_refine(units, path):
    """MediatedChain: incumbent objective and cumulative regret side by side."""
    methods = ('BO', 'BO-S', 'CBO', 'QCBO', 'HQCBO')
    fig, axes = plt.subplots(1, 2, figsize=plotstyle.size('column', 0.62))
    for ax, (letter, title, key, cumulative, ylabel) in zip(axes, [
            ('a', 'MediatedChain', 'recommendation_population', False, 'Incumbent objective'),
            ('b', 'Cumulative regret', 'recommendation_regret', True, 'Cumulative regret')]):
        for method in methods:
            group = select(units, scm='MediatedChain', cond='C0', method=method)
            require(group, f'missing MediatedChain {method} results')
            draw(ax, *cost_curves(group, key, cumulative), method)
        plotstyle.panel_title(ax, letter, title)
        ax.set_xlabel('Intervention cost')
        ax.set_ylabel(ylabel)
        ax.set_ylim(bottom=0)
    refined = [u['refined_at'] for u in select(units, scm='MediatedChain', method='HQCBO') if u['refined_at'] is not None]
    if refined:
        axes[0].axvline(statistics.median(refined), color=plotstyle.GREEN, ls=':', lw=0.8, zorder=1)
    order = ['CBO', 'QCBO', 'HQCBO', 'BO', 'BO-S']
    fig.legend(plotstyle.legend_handles(order), order, loc='outside upper center', ncol=5,
               handlelength=1.8, columnspacing=0.9)
    save(fig, path)
    return refined


def figure_family(dynamic, mcbo, path):
    fig = plt.figure(figsize=plotstyle.size('text', 0.62))
    grid = fig.add_gridspec(2, 6)
    top = [fig.add_subplot(grid[0, 2 * i:2 * i + 2]) for i in range(3)]
    bottom = [fig.add_subplot(grid[1, 3 * i:3 * i + 3]) for i in range(2)]
    variants = [('DCBO', 'DCBO', 'native'), ('DCBO (matched exploration set)', 'DCBO', 'coarse'), ('QDCBO', 'QDCBO', 'native')]
    for i, (ax, (setup, name)) in enumerate(zip(top, FAMILY_PANELS)):
        for label, algo, menu in variants:
            group = select(dynamic, setup=setup, algo=algo, action_menu=menu)
            require(group, f'missing dynamic {setup} {label} results')
            slices = sorted({t for t, _, _ in group[0]['trials']})
            per_slice = max(k for _, k, _ in group[0]['trials'])
            for t in slices:
                x = [t * per_slice + k for tt, k, _ in group[0]['trials'] if tt == t]
                matrix = [[v for tt, _, v in u['trials'] if tt == t] for u in group]
                draw(ax, np.array(x), matrix, label, steps=False)
            for t in slices[1:]:
                ax.axvline(t * per_slice + 0.5, color='0.75', lw=0.5)
        ax.set_xticks([1] + [per_slice * (t + 1) for t in slices])
        plotstyle.panel_title(ax, 'abc'[i], name)
        ax.set_xlabel('Intervention trial')
    top[0].set_ylabel('Incumbent objective')
    labels = [l for l, _, _ in variants]
    top[1].legend(plotstyle.legend_handles(labels), labels, loc='lower center', bbox_to_anchor=(0.5, 1.12), ncol=3)
    variants = [('MCBO', 'MCBO', 'full'), ('MCBO (matched exploration set)', 'MCBO', 'coarse'), ('QMCBO', 'QMCBO', 'coarse')]
    for i, (ax, (env, name)) in enumerate(zip(bottom, MODEL_BASED)):
        for label, algo, menu in variants:
            group = select(mcbo, env_name=env, algo=algo, menu=menu, misspec='')
            require(group, f'missing model-based {env} {label} results')
            draw(ax, np.arange(1, len(group[0]['rewards']) + 1), [u['rewards'] for u in group], label, steps=False)
        plotstyle.panel_title(ax, 'de'[i], name)
        ax.set_xlabel('Intervention trial')
    bottom[0].set_ylabel('Incumbent reward')
    labels = [l for l, _, _ in variants]
    bottom[0].legend(plotstyle.legend_handles(labels), labels, loc='lower left', ncol=1)
    save(fig, path)


