def style_axis(ax, letter_title):
    ax.set_title(letter_title, fontsize=8, loc='left')
    ax.tick_params(labelsize=7)
    ax.grid(axis='y', lw=0.4, alpha=0.4)
    for side in ('top', 'right'):
        ax.spines[side].set_visible(False)


def plot_band(ax, x, matrix, label):
    colour, ls = STYLE[label]
    mean, half = band(matrix)
    ax.plot(x, mean, color=colour, ls=ls, lw=1.3, label=label)
    if not np.all(np.isnan(half)):
        ax.fill_between(x, mean - half, mean + half, color=colour, alpha=0.15, lw=0)


def cost_curves(units, key, cumulative=False):
    """Seed-by-cost matrix restricted to costs reached by every seed."""
    rows = [{c['cost']: c[key] for c in u['checkpoints']} for u in units]
    costs = sorted(set.intersection(*(set(r) for r in rows)))
    matrix = np.array([[r[c] for c in costs] for r in rows])
    if cumulative:
        matrix = np.cumsum(matrix, axis=1)
    return np.array(costs), matrix


def figure_cost_indexed(units, path):
    fig, axes = plt.subplots(2, 1, figsize=(3.3, 4.2))
    panels = [('(a) ParallelParent', 'ParallelParent', 'A0', 'A1'),
              ('(b) FrontDoor', 'FrontDoor', 'B0', 'B1')]
    for ax, (title, scm, correct, edited) in zip(axes, panels):
        series = [(m, select(units, scm=scm, cond=correct, method=m)) for m in ('CBO', 'QCBO', 'BO', 'BO-S', 'CBO-NP')]
        series.append(('CBO (misspecified)', select(units, scm=scm, cond=edited, method='CBO')))
        for label, group in series:
            require(group, f'missing {scm} {label} results')
            plot_band(ax, *cost_curves(group, 'recommendation_population'), label)
        style_axis(ax, title)
        ax.set_xlabel('Intervention cost', fontsize=8)
        ax.set_ylabel('Incumbent objective', fontsize=8)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='lower center', ncol=3, fontsize=7, frameon=False, bbox_to_anchor=(0.5, -0.06))
    fig.tight_layout()
    fig.savefig(path, bbox_inches='tight')
    plt.close(fig)


def figure_minimal_refine(units, path):
    fig, axes = plt.subplots(2, 1, figsize=(3.3, 4.2))
    methods = ('BO', 'BO-S', 'CBO', 'QCBO', 'HQCBO')
    for ax, (title, key, cumulative, ylabel) in zip(axes, [
            ('(a) MediatedChain', 'recommendation_population', False, 'Incumbent objective'),
            ('(b) Cumulative regret', 'recommendation_regret', True, 'Cumulative incumbent regret')]):
        for method in methods:
            group = select(units, scm='MediatedChain', cond='C0', method=method)
            require(group, f'missing MediatedChain {method} results')
            plot_band(ax, *cost_curves(group, key, cumulative), method)
        style_axis(ax, title)
        ax.set_xlabel('Intervention cost', fontsize=8)
        ax.set_ylabel(ylabel, fontsize=8)
    refined = [u['refined_at'] for u in select(units, scm='MediatedChain', method='HQCBO') if u['refined_at'] is not None]
    if refined:
        axes[0].axvline(statistics.median(refined), color=STYLE['HQCBO'][0], ls=':', lw=1)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='lower center', ncol=5, fontsize=7, frameon=False, bbox_to_anchor=(0.5, -0.04))
    fig.tight_layout()
    fig.savefig(path, bbox_inches='tight')
    plt.close(fig)
    return refined


def figure_family(dynamic, mcbo, path):
    fig = plt.figure(figsize=(7.0, 4.6))
    grid = fig.add_gridspec(2, 6, height_ratios=[1, 1], hspace=0.75, wspace=1.4)
    top = [fig.add_subplot(grid[0, 2 * i:2 * i + 2]) for i in range(3)]
    bottom = [fig.add_subplot(grid[1, 3 * i:3 * i + 3]) for i in range(2)]
    variants = [('DCBO', 'DCBO', 'native'), ('DCBO (matched exploration set)', 'DCBO', 'coarse'), ('QDCBO', 'QDCBO', 'native')]
    for i, (ax, (setup, name)) in enumerate(zip(top, FAMILY_PANELS)):
        for label, algo, menu in variants:
            group = select(dynamic, setup=setup, algo=algo, action_menu=menu)
            require(group, f'missing dynamic {setup} {label} results')
            slices = sorted({t for t, _, _ in group[0]['trials']})
            per_slice = max(k for _, k, _ in group[0]['trials'])
            for t in slices:
                x = [t * per_slice + k for tt, k, _ in group[0]['trials'] if tt == t]
                matrix = [[v for tt, _, v in u['trials'] if tt == t] for u in group]
                plot_band(ax, x, matrix, label)
                if label != variants[0][0] or t != slices[0]:
                    ax.lines[-1].set_label('_nolegend_')
            for t in slices[1:]:
                ax.axvline(t * per_slice + 0.5, color='0.6', lw=0.6)
        ax.set_xticks([1] + [per_slice * (t + 1) for t in slices])
        style_axis(ax, f'({"abc"[i]}) {name}')
        ax.set_xlabel('Intervention trial', fontsize=8)
    top[0].set_ylabel('Incumbent objective', fontsize=8)
    handles = [plt.Line2D([], [], color=STYLE[l][0], ls=STYLE[l][1], lw=1.3) for l, _, _ in variants]
    fig.legend(handles, [l for l, _, _ in variants], loc='center', ncol=3, fontsize=7, frameon=False,
               bbox_to_anchor=(0.5, 0.505))
    variants = [('MCBO', 'MCBO', 'full'), ('MCBO (matched exploration set)', 'MCBO', 'coarse'), ('QMCBO', 'QMCBO', 'coarse')]
    for i, (ax, (env, name)) in enumerate(zip(bottom, MODEL_BASED)):
        for label, algo, menu in variants:
            group = select(mcbo, env_name=env, algo=algo, menu=menu, misspec='')
            require(group, f'missing model-based {env} {label} results')
            plot_band(ax, np.arange(1, len(group[0]['rewards']) + 1), [u['rewards'] for u in group], label)
        style_axis(ax, f'({"de"[i]}) {name}')
        ax.set_xlabel('Intervention trial', fontsize=8)
    bottom[0].set_ylabel('Incumbent reward', fontsize=8)
    handles = [plt.Line2D([], [], color=STYLE[l][0], ls=STYLE[l][1], lw=1.3) for l, _, _ in variants]
    fig.legend(handles, [l for l, _, _ in variants], loc='center', ncol=3, fontsize=7, frameon=False,
               bbox_to_anchor=(0.5, 0.0))
    fig.savefig(path, bbox_inches='tight')
    plt.close(fig)


