def fmt(values, digits):
    mean, half = statistics.mean(values), half_width(values)
    text = f'{mean:.{digits}f}'.replace('-', '$-$')
    if not math.isnan(half):
        text += f' $\\pm$ {half:.{digits}f}'
    return mean, text


def table_family(dynamic, mcbo, path):
    lines = [HEADER, '\\begin{tabular}{lccc}\n\\toprule\n',
             'SCM & DCBO & \\begin{tabular}[c]{@{}c@{}}DCBO\\\\(matched exploration set)\\end{tabular} & QDCBO \\\\\n\\midrule\n',
             '\\multicolumn{4}{l}{\\textbf{Dynamic}: sum of committed outcomes $\\downarrow$} \\\\\n']
    blocks = [(DYNAMIC, dynamic, 'setup', 'committed_slice_sum', min,
               [('DCBO', 'native'), ('DCBO', 'coarse'), ('QDCBO', 'native')], 'action_menu', 'algo'),
              (MODEL_BASED, mcbo, 'env_name', 'endpoint', max,
               [('MCBO', 'full'), ('MCBO', 'coarse'), ('QMCBO', 'coarse')], 'menu', 'algo')]
    for index, (rows, units, key, metric, best, columns, menu_key, algo_key) in enumerate(blocks):
        if index:
            lines.append('\\midrule\\midrule\n\\multicolumn{4}{l}{\\textbf{Model-based}: final incumbent reward $\\uparrow$} \\\\\n'
                         'SCM & MCBO & \\begin{tabular}[c]{@{}c@{}}MCBO\\\\(matched exploration set)\\end{tabular} & QMCBO \\\\\n\\midrule\n')
        for name, label in rows:
            cells = []
            for algo, menu in columns:
                group = [u for u in units if u[key] == name and u[algo_key] == algo and u[menu_key] == menu and not u.get('misspec')]
                require(group, f'missing {name} {algo} {menu} results')
                cells.append(fmt([u[metric] for u in group], 3))
            winner = best(round(m, 3) for m, _ in cells)
            text = [f'\\textbf{{{t}}}' if round(m, 3) == winner else t for m, t in cells]
            lines.append(f'{label} & ' + ' & '.join(text) + ' \\\\\n')
    lines.append('\\bottomrule\n\\end{tabular}\n')
    path.write_text(''.join(lines))


def table_taxonomy(summary, path):
    checks = summary['protected_checks']
    require(checks and all(c['exact_equal'] for c in checks), 'protected QCBO traces differ between paired graph conditions')
    path.write_text(HEADER + r'''\begin{tabular}{llcccc}
\toprule
 & & Quotient & Fine MIS & Fine prior & \\
Condition & Supplied graph & changed & changed & changed & Isolates \\
\midrule
A0 (PP) & correct & -- & -- & -- & reference \\
A1 (PP) & delete $X_1\to Y$ & no & yes & -- & arm loss \\
\midrule
B0 (FD) & correct & -- & -- & -- & reference \\
B1 (FD) & add $X_1\leftrightarrow M$ & no & no & yes & prior corruption \\
\midrule
C0 (MC) & correct & -- & -- & -- & coarsening price, refinement \\
\bottomrule
\end{tabular}
''')


def table_ablations(units, path):
    lines = [HEADER, '\\begin{tabular}{llrr}\n\\toprule\n',
             'Condition & Method & Final incumbent regret & Cumulative incumbent regret \\\\\n']
    for scm, cond, short in CONDITIONS:
        rows = []
        for method in sorted({u['method'] for u in select(units, scm=scm, cond=cond)}):
            group = select(units, scm=scm, cond=cond, method=method)
            final = fmt([u['final_recommendation_regret'] for u in group], 3)
            area = fmt([u['cost_integrated_recommendation_regret'] for u in group], 2)
            rows.append((method, final, area))
        require(rows, f'missing {scm} {cond} results')
        winner = min(rows, key=lambda r: (round(r[1][0], 3), r[2][0]))[0]
        lines.append('\\midrule\n')
        for method, (_, final), (_, area) in rows:
            cells = [f'{short} {cond}', method, final, area]
            if method == winner:
                cells = [f'\\textbf{{{c}}}' for c in cells]
            lines.append(' & '.join(cells) + ' \\\\\n')
    lines.append('\\bottomrule\n\\end{tabular}\n')
    path.write_text(''.join(lines))


def table_costs(units, path):
    def number(values):
        mean = statistics.mean(values)
        return str(int(mean)) if float(mean).is_integer() else f'{mean:.1f}'
    lines = [HEADER, '\\begin{tabular}{llrrr}\n\\toprule\n', 'Condition & Method & Budget & Init. & Sequential \\\\\n']
    for scm, cond, short in CONDITIONS:
        lines.append('\\midrule\n')
        for method in sorted({u['method'] for u in select(units, scm=scm, cond=cond)}):
            group = select(units, scm=scm, cond=cond, method=method)
            sequential = [u['actual_cost'] - u['init_cost'] - u['split_cost'] for u in group]
            lines.append(f'{short} {cond} & {method} & {number([u["budget"] for u in group])} & '
                         f'{number([u["init_cost"] for u in group])} & {number(sequential)} \\\\\n')
    lines.append('\\bottomrule\n\\end{tabular}\n')
    path.write_text(''.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--results', type=Path, default=Path('results/paper'))
    parser.add_argument('--out', type=Path, default=Path('results/paper_outputs'))
    parser.add_argument('--suites', nargs='+', choices=SUITES, default=list(SUITES),
                        help='Suites to report; Figure 4 and Table 1 need both dynamic and mcbo')
    parser.add_argument('--smoke', action='store_true', help='Report pilot results; never paper evidence')
    args = parser.parse_args()
    analyze = load_analyzer()
    (args.out / 'figures').mkdir(parents=True, exist_ok=True)
    (args.out / 'tables').mkdir(parents=True, exist_ok=True)
    written = []
    if 'static' in args.suites:
        summary = audited(analyze, args.results, 'static', args.smoke)
        units = static_units(args.results, args.smoke, summary)
        figure_cost_indexed(units, args.out / 'figures' / 'cost_indexed.pdf')
        refined = figure_minimal_refine(units, args.out / 'figures' / 'minimal_refine.pdf')
        if refined:
            print(f'HQCBO refinement completes at cost {sorted(set(refined))} (Figure 3 marks the median)')
        table_taxonomy(summary, args.out / 'tables' / 'minimal_taxonomy.tex')
        table_ablations(units, args.out / 'tables' / 'minimal_ablations.tex')
        table_costs(units, args.out / 'tables' / 'cost_accounting.tex')
        written += ['figures/cost_indexed.pdf', 'figures/minimal_refine.pdf', 'tables/minimal_taxonomy.tex',
                    'tables/minimal_ablations.tex', 'tables/cost_accounting.tex']
    if 'dynamic' in args.suites and 'mcbo' in args.suites:
        dynamic = dynamic_units(args.results, args.smoke, audited(analyze, args.results, 'dynamic', args.smoke))
        mcbo = mcbo_units(args.results, args.smoke, audited(analyze, args.results, 'mcbo', args.smoke))
        figure_family(dynamic, mcbo, args.out / 'figures' / 'family_suite.pdf')
        table_family(dynamic, mcbo, args.out / 'tables' / 'family_effects.tex')
        written += ['figures/family_suite.pdf', 'tables/family_effects.tex']
    elif 'dynamic' in args.suites or 'mcbo' in args.suites:
        parser.error('Figure 4 and Table 1 combine the dynamic and mcbo suites; request both')
    for name in written:
        print(args.out / name)
    if args.smoke:
        print('Smoke outputs: pipeline check only, not paper evidence.')


if __name__ == '__main__':
    main()
