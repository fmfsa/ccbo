#!/usr/bin/env python3
"""Regenerate the paper's figures and tables from audited experiment results.

Every suite is first checked with ``experiments/analyze.py``; figures and
tables are written only when the audit reports no failures. Paper outputs
also require the complete declared matrix. ``--smoke`` accepts pilot runs so
the pipeline can be exercised end to end, but its outputs are not evidence.

Outputs (file names match the manuscript's ``\\includegraphics``/``\\input``):
  figures/cost_indexed.pdf     Figure 2  (ParallelParent, FrontDoor)
  figures/minimal_refine.pdf   Figure 3  (MediatedChain)
  figures/family_suite.pdf     Figure 4  (dynamic and model-based families)
  tables/family_effects.tex    Table 1
  tables/minimal_taxonomy.tex  Table 2
  tables/minimal_ablations.tex Table 3
  tables/cost_accounting.tex   Table 4
"""
import argparse
import csv
import importlib.util
import json
import math
from pathlib import Path
import statistics

import numpy as np
from scipy import stats
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

SUITES = ('static', 'dynamic', 'mcbo')
HEADER = '% Generated by experiments/report.py -- do not edit.\n'

CONDITIONS = [('ParallelParent', 'A0', 'PP'), ('ParallelParent', 'A1', 'PP'),
              ('FrontDoor', 'B0', 'FD'), ('FrontDoor', 'B1', 'FD'),
              ('MediatedChain', 'C0', 'MC')]
DYNAMIC = [('stat', 'Stationary'), ('ind', 'Independent'), ('nonstat_regularized', 'Nonstationary')]
FAMILY_PANELS = [('stat', 'Stationary'), ('ind', 'Independent'), ('nonstat_regularized', 'Nonstationary (regularized)')]
MODEL_BASED = [('ToyGraph', 'ToyGraph'), ('PSAGraph', 'PSAGraph')]

# label -> (colour, linestyle); Okabe-Ito palette.
STYLE = {
    'CBO': ('#0072B2', '-'), 'QCBO': ('#D55E00', '--'), 'BO': ('#E69F00', ':'),
    'BO-S': ('#555555', '-.'), 'CBO-NP': ('#CC79A7', '-.'), 'CBO (misspecified)': ('#56B4E9', '--'),
    'HQCBO': ('#009E73', '-'),
    'DCBO': ('#0072B2', '-'), 'DCBO (matched exploration set)': ('#009E73', '-.'), 'QDCBO': ('#D55E00', '--'),
    'MCBO': ('#0072B2', '-'), 'MCBO (matched exploration set)': ('#009E73', '-.'), 'QMCBO': ('#D55E00', '--'),
}


def require(ok, message):
    if not ok:
        raise SystemExit('report: ' + message)


def load_analyzer():
    path = Path(__file__).with_name('analyze.py')
    spec = importlib.util.spec_from_file_location('paper_experiment_analysis', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def half_width(values):
    """Two-sided 95% Student-t half-width; NaN for a single seed."""
    n = len(values)
    if n < 2:
        return float('nan')
    return float(stats.t.ppf(0.975, n - 1) * statistics.stdev(values) / math.sqrt(n))


def band(matrix):
    """Mean and 95% half-width across seeds (rows) for each column."""
    matrix = np.asarray(matrix, dtype=float)
    mean = matrix.mean(axis=0)
    n = matrix.shape[0]
    if n < 2:
        return mean, np.full_like(mean, np.nan)
    return mean, stats.t.ppf(0.975, n - 1) * matrix.std(axis=0, ddof=1) / math.sqrt(n)


def audited(analyze, results, suite, smoke):
    summary = analyze.summarize(results, suite, smoke)
    require(not summary['failures'], f'{suite} audit failed: {summary["failures"][:3]}')
    require(summary['valid_units'] > 0, f'no {suite} results under {results}')
    if not smoke:
        require(summary['complete'], f'{suite} matrix incomplete ({summary["missing_count"]} missing units)')
    return summary


def unit_dir(results, smoke, suite, unit_id):
    return Path(results) / ('smoke' if smoke else 'paper') / suite / unit_id / 'result'


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def static_units(results, smoke, summary):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, 'static', row['unit_id'])
        scores = json.loads((folder / 'scores.json').read_text())
        run = json.loads((folder / 'summary.json').read_text())
        events = json.loads((folder / 'events.json').read_text())
        refinement = run.get('backend', {}).get('refinement') or {}
        refined_at = None
        if refinement.get('accepted'):
            refined_at = events[refinement['split_event_ids'][-1]]['cum_cost']
        units.append(dict(row, checkpoints=scores['checkpoints'], init_cost=run['init_cost'],
                          split_cost=run.get('split_init_cost', 0), budget=run['budget'],
                          refined_at=refined_at))
    return units


def dynamic_units(results, smoke, summary):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, 'dynamic', row['unit_id'])
        with next(folder.glob('*.csv')).open(newline='') as f:
            trials = [r for r in csv.DictReader(f) if r['eligible_recommendation'] == 'True']
        units.append(dict(row, trials=[(int(r['time_index']), int(r['trial_index']),
                                        float(r['population_recommendation_mean'])) for r in trials]))
    return units


def mcbo_units(results, smoke, summary):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, 'mcbo', row['unit_id'])
        with next(folder.glob('*.csv')).open(newline='') as f:
            trials = sorted((int(r['trial_number']), float(r['recommendation_population_estimate']))
                            for r in csv.DictReader(f))
        units.append(dict(row, rewards=[v for _, v in trials]))
    return units


def select(units, **fields):
    return [u for u in units if all(u.get(k) == v for k, v in fields.items())]


