def static_units(results, smoke, summary, suite='static'):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, suite, row['unit_id'])
        scores = json.loads((folder / 'scores.json').read_text())
        run = json.loads((folder / 'summary.json').read_text())
        events = json.loads((folder / 'events.json').read_text())
        backend = run.get('backend', {})
        refinements = backend.get('refinements')
        if refinements is None:
            refinements = [backend['refinement']] if backend.get('refinement') else []
        accepted = [r for r in refinements if r.get('accepted')]
        # Refinement completes after its split design; without one (v4: new arms
        # get no data) it completes at the trigger event itself.
        refined_at = None
        if accepted:
            last = accepted[-1]
            ids = last.get('split_event_ids') or [last['trigger_event_id']]
            refined_at = events[ids[-1]]['cum_cost']
        trial_of = {e['event_id']: e.get('trial', 0) for e in events}
        units.append(dict(row, checkpoints=scores['checkpoints'], scored_events=scores['scored_events'],
                          trials=run.get('trials', 0),
                          trial_points=[(trial_of[r['event_id']], r) for r in scores['scored_events']],
                          init_cost=run['init_cost'], split_cost=run.get('split_init_cost', 0),
                          init_points=run.get('init_points', 0), observe_trials=run.get('observe_trials', 0),
                          budget=run['budget'], refined_at=refined_at,
                          triggered_at=[events[r['trigger_event_id']]['cum_cost'] for r in refinements]))
    return units


def dynamic_units(results, smoke, summary):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, 'dynamic', row['unit_id'])
        with next(folder.glob('*.csv')).open(newline='') as f:
            trials = [r for r in csv.DictReader(f) if r['eligible_recommendation'] == 'True']
        units.append(dict(row, trials=[(int(r['time_index']), int(r['trial_index']),
                                        float(r['population_recommendation_mean'])) for r in trials]))
    return units


def mcbo_units(results, smoke, summary):
    units = []
    for row in summary['units']:
        folder = unit_dir(results, smoke, 'mcbo', row['unit_id'])
        with next(folder.glob('*.csv')).open(newline='') as f:
            trials = sorted((int(r['trial_number']), float(r['recommendation_population_estimate']))
                            for r in csv.DictReader(f))
        units.append(dict(row, rewards=[v for _, v in trials]))
    return units


def select(units, **fields):
    return [u for u in units if all(u.get(k) == v for k, v in fields.items())]


